class SmartEvolution:
    """
    Analyzes Blue Team's mistakes to find blind spots.
    
    Process:
    1. After Blue Team evaluates, collect all FALSE NEGATIVES (missed fraud)
    2. Compare feature distributions of CAUGHT vs MISSED fraud
    3. Identify which parameters made fraud harder to detect
    4. Shift Red Team parameters TOWARD the blind spot
    
    This is NOT hardcoded rules — it's data-driven curriculum learning.
    """
    
    def analyze_blind_spots(self, predictions, true_labels, features, feature_names):
        """
        Find what the Blue Team misses.
        
        Args:
            predictions: Model's predicted labels (0/1)
            true_labels: Ground truth labels (0/1)
            features: Feature matrix (node or edge features)
            feature_names: List of feature column names
        
        Returns:
            dict of blind spots: {feature_name: {missed_mean, caught_mean, shift}}
        """
        # Separate caught (True Positives) vs missed (False Negatives) fraud
        is_fraud = true_labels == 1
        is_caught = (predictions == 1) & is_fraud     # TP
        is_missed = (predictions == 0) & is_fraud      # FN
        
        if is_missed.sum() == 0:
            return {}  # No blind spots — Blue Team caught everything
        
        if is_caught.sum() == 0:
            return {}  # Blue Team caught nothing — no comparison possible
        
        blind_spots = {}
        
        for i, fname in enumerate(feature_names):
            caught_vals = features[is_caught, i]
            missed_vals = features[is_missed, i]
            
            caught_mean = float(np.mean(caught_vals)) if len(caught_vals) > 0 else 0
            missed_mean = float(np.mean(missed_vals)) if len(missed_vals) > 0 else 0
            
            # Only report if there's a meaningful difference
            diff = abs(missed_mean - caught_mean)
            if diff > 0.01:  # Threshold for meaningful difference
                blind_spots[fname] = {
                    'caught_mean': round(caught_mean, 4),
                    'missed_mean': round(missed_mean, 4),
                    'shift': round(missed_mean - caught_mean, 4),
                    'direction': 'increase' if missed_mean > caught_mean else 'decrease'
                }
        
        return blind_spots
    
    def generate_report(self, blind_spots, epoch):
        """Generate a human-readable evolution report for the demo."""
        report = f"\n{'='*50}\n"
        report += f"  🔴 RED TEAM EVOLUTION REPORT — Epoch {epoch}\n"
        report += f"{'='*50}\n"
        
        if not blind_spots:
            report += "  No blind spots found — Blue Team caught everything!\n"
            report += "  Red Team will try a completely different topology next epoch.\n"
            return report
        
        report += f"  Blue Team Blind Spots Detected: {len(blind_spots)}\n\n"
        
        for fname, info in blind_spots.items():
            report += f"  📌 {fname}:\n"
            report += f"     Caught fraud mean: {info['caught_mean']:.4f}\n"
            report += f"     Missed fraud mean: {info['missed_mean']:.4f}\n"
            report += f"     Shift: {info['shift']:+.4f} ({info['direction']})\n"
            report += f"     → Red Team will {info['direction']} this parameter\n\n"
        
        return report


