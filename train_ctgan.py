"""
MASTERCARD AI DEFENSE LAB — Phase 1B: CTGAN Feature Engine Training

Purpose:
    Train CTGAN on seed data to learn REALISTIC feature distributions.
    CTGAN learns: amount patterns, timing patterns, dwell times, rail distributions.
    CTGAN does NOT learn: graph structure (that's the Topology Simulator's job).

Flow:
    1. Load seed CSVs (from generate_seed_data.py output)
    2. Feature engineer (extract hour, day_of_week from timestamp)
    3. Train CTGAN_legit on legitimate transaction features
    4. Train CTGAN_fraud on fraud transaction features  
    5. Sample synthetic data from both models
    6. Run Fidelity Validation (KS test, timing check, distribution sanity)
    7. Save trained models as .pkl files

Why TWO CTGANs?
    - CTGAN_legit learns: "What do normal Indian payments look like?"
      (log-normal amounts, UPI-heavy, long dwell times, business-hour timing)
    - CTGAN_fraud learns: "What do fraud transaction FEATURES look like?"
      (structured amounts near ₹10K, short dwell times, specific rail patterns)
    
    The Graph Topology Simulator decides WHO sends to WHOM (structure).
    CTGAN decides HOW MUCH, WHEN, and on WHICH RAIL (features).

Dependencies:
    pip install ctgan pandas numpy scipy scikit-learn
"""

import pandas as pd
import numpy as np
import pickle
import os
import warnings
from datetime import datetime

warnings.filterwarnings('ignore')

# =====================================================================
# 1. LOAD & PREPARE SEED DATA
# =====================================================================

def load_seed_data(txn_path='seed_transactions_edges.csv', 
                   accounts_path='seed_accounts_nodes.csv'):
    """Load CSVs generated by generate_seed_data.py"""
    
    txn_df = pd.read_csv(txn_path)
    accounts_df = pd.read_csv(accounts_path)
    
    # Parse timestamps
    txn_df['timestamp'] = pd.to_datetime(txn_df['timestamp'])
    
    print(f"✅ Loaded {len(txn_df)} transactions, {len(accounts_df)} accounts")
    print(f"   Fraud ratio: {txn_df['is_fraud'].mean()*100:.2f}%")
    
    return txn_df, accounts_df


def engineer_ctgan_features(txn_df):
    """
    Extract the features that CTGAN should learn.
    
    CTGAN LEARNS these columns (feature distributions):
      - amount          : Transaction value (continuous)
      - rail            : Payment rail (categorical: BANK/UPI/WALLET/CRYPTO)
      - dwell_time_seconds: Time gap since last received funds (continuous)
      - hour_of_day     : 0-23, extracted from timestamp (discrete)
      - day_of_week     : 0-6 (Mon-Sun), extracted from timestamp (discrete)
      - is_structured   : Binary flag for threshold-proximity (discrete)
    
    CTGAN IGNORES these columns (graph structure / identity):
      - txn_id          : Random UUID, no pattern to learn
      - sender/receiver : Graph topology, not features
      - device_hash     : Stateful, pulled from account metadata
      - ip_subnet       : Stateful, pulled from account metadata
      - shared_hash     : Cross-rail linking mechanism
      - timestamp       : We extract hour/day instead
      - is_fraud        : Label, not a feature to generate
    """
    
    df = txn_df.copy()
    
    # Extract time features from timestamp
    df['hour_of_day'] = df['timestamp'].dt.hour
    df['day_of_week'] = df['timestamp'].dt.dayofweek  # 0=Monday, 6=Sunday
    
    # The columns CTGAN will train on
    ctgan_columns = [
        'amount',
        'rail',
        'dwell_time_seconds',
        'hour_of_day',
        'day_of_week',
        'is_structured'
    ]
    
    # Which of these are discrete/categorical (CTGAN needs to know)
    discrete_columns = [
        'rail',
        'hour_of_day',
        'day_of_week',
        'is_structured'
    ]
    
    return df, ctgan_columns, discrete_columns


# =====================================================================
# 2. TRAIN CTGAN MODELS
# =====================================================================

def train_ctgan(data, ctgan_columns, discrete_columns, 
                epochs=300, batch_size=500, model_name="ctgan"):
    """
    Train a CTGAN model on the given data.
    
    Args:
        data: DataFrame with all columns
        ctgan_columns: Which columns CTGAN should learn
        discrete_columns: Which of those are categorical/discrete
        epochs: Training iterations (300 = good balance of quality vs speed)
        batch_size: Samples per training batch
        model_name: For logging
    
    Returns:
        Trained CTGAN model
    """
    from ctgan import CTGAN
    
    train_data = data[ctgan_columns].copy()
    
    # Handle any NaN values
    train_data = train_data.fillna(0)
    
    print(f"\n{'='*50}")
    print(f"  Training {model_name}")
    print(f"{'='*50}")
    print(f"  Rows:     {len(train_data)}")
    print(f"  Columns:  {ctgan_columns}")
    print(f"  Discrete: {discrete_columns}")
    print(f"  Epochs:   {epochs}")
    print(f"  Batch:    {batch_size}")
    
    # Initialize CTGAN
    model = CTGAN(
        epochs=epochs,
        batch_size=batch_size,
        verbose=True  # Show training progress
    )
    
    # Train
    print(f"\n  🔄 Training started...")
    start_time = datetime.now()
    
    model.fit(
        train_data,
        discrete_columns=discrete_columns
    )
    
    elapsed = (datetime.now() - start_time).total_seconds()
    print(f"  ✅ Training complete in {elapsed:.1f}s")
    
    return model


def sample_and_preview(model, n_samples, ctgan_columns, model_name="ctgan"):
    """Generate synthetic samples and show a quick preview."""
    
    print(f"\n  📊 Sampling {n_samples} synthetic rows from {model_name}...")
    synthetic = model.sample(n_samples)
    
    print(f"\n  Preview ({model_name} synthetic data):")
    print(f"  {'─'*50}")
    print(synthetic.describe().round(2).to_string())
    print(f"\n  Rail distribution:")
    print(f"  {synthetic['rail'].value_counts().to_dict()}")
    
    return synthetic


# =====================================================================
# 3. FIDELITY VALIDATION
# =====================================================================

def run_fidelity_checks(real_data, synthetic_data, model_name="ctgan"):
    """
    Fidelity Validator — ensures CTGAN output is statistically realistic.
    
    From solution_design.md (Section 5.4):
    - KS Test on amount distribution (p > 0.05 = similar)
    - Timing check (75%+ txns in business hours 8AM-10PM)
    - Dwell time distribution sanity
    - Rail distribution similarity
    
    This is the Quality Gate between Red Team and Blue Team.
    """
    from scipy.stats import ks_2samp
    
    print(f"\n{'='*50}")
    print(f"  FIDELITY VALIDATION: {model_name}")
    print(f"{'='*50}")
    
    results = {}
    
    # ─── Test 1: Amount Distribution (KS Test) ───
    ks_stat, p_value = ks_2samp(
        real_data['amount'].values,
        synthetic_data['amount'].values
    )
    results['amount_ks_stat'] = round(ks_stat, 4)
    results['amount_ks_pvalue'] = round(p_value, 4)
    results['amount_pass'] = p_value > 0.05
    
    status = "✅ PASS" if results['amount_pass'] else "❌ FAIL"
    print(f"\n  1. Amount Distribution (KS Test):")
    print(f"     KS Statistic: {ks_stat:.4f}")
    print(f"     P-Value:      {p_value:.4f}")
    print(f"     Result:       {status}")
    print(f"     (p > 0.05 means distributions are similar)")
    
    # ─── Test 2: Timing Realism ───
    syn_hours = synthetic_data['hour_of_day']
    business_ratio = ((syn_hours >= 8) & (syn_hours <= 22)).mean()
    results['business_hour_ratio'] = round(business_ratio, 4)
    results['timing_pass'] = business_ratio > 0.70
    
    status = "✅ PASS" if results['timing_pass'] else "❌ FAIL"
    print(f"\n  2. Timing Realism:")
    print(f"     Business hours (8AM-10PM): {business_ratio:.2%}")
    print(f"     Result:                    {status}")
    print(f"     (Should be >70% for Indian market)")
    
    # ─── Test 3: Dwell Time Sanity ───
    real_dwell_mean = real_data['dwell_time_seconds'].mean()
    syn_dwell_mean = synthetic_data['dwell_time_seconds'].mean()
    dwell_ratio = syn_dwell_mean / max(real_dwell_mean, 1)
    results['dwell_ratio'] = round(dwell_ratio, 4)
    results['dwell_pass'] = 0.5 < dwell_ratio < 2.0  # Within 2x of real
    
    status = "✅ PASS" if results['dwell_pass'] else "❌ FAIL"
    print(f"\n  3. Dwell Time Sanity:")
    print(f"     Real mean:      {real_dwell_mean:.0f}s")
    print(f"     Synthetic mean: {syn_dwell_mean:.0f}s")
    print(f"     Ratio:          {dwell_ratio:.2f}x")
    print(f"     Result:         {status}")
    print(f"     (Should be within 0.5x - 2.0x of real)")
    
    # ─── Test 4: Rail Distribution Similarity ───
    real_rail_dist = real_data['rail'].value_counts(normalize=True).sort_index()
    syn_rail_dist = synthetic_data['rail'].value_counts(normalize=True).sort_index()
    
    # Align indices
    all_rails = sorted(set(real_rail_dist.index) | set(syn_rail_dist.index))
    real_probs = [real_rail_dist.get(r, 0) for r in all_rails]
    syn_probs = [syn_rail_dist.get(r, 0) for r in all_rails]
    
    # Jensen-Shannon-like distance (simple max absolute diff)
    max_rail_diff = max(abs(r - s) for r, s in zip(real_probs, syn_probs))
    results['rail_max_diff'] = round(max_rail_diff, 4)
    results['rail_pass'] = max_rail_diff < 0.15  # Within 15% per rail
    
    status = "✅ PASS" if results['rail_pass'] else "❌ FAIL"
    print(f"\n  4. Rail Distribution:")
    print(f"     Real:      {dict(zip(all_rails, [f'{p:.2%}' for p in real_probs]))}")
    print(f"     Synthetic: {dict(zip(all_rails, [f'{p:.2%}' for p in syn_probs]))}")
    print(f"     Max diff:  {max_rail_diff:.2%}")
    print(f"     Result:    {status}")
    
    # ─── Overall Verdict ───
    all_passed = all([
        results['amount_pass'],
        results['timing_pass'],
        results['dwell_pass'],
        results['rail_pass']
    ])
    results['overall_pass'] = all_passed
    
    print(f"\n  {'='*50}")
    if all_passed:
        print(f"  ✅ OVERALL: ALL FIDELITY CHECKS PASSED")
        print(f"  CTGAN output is statistically realistic.")
        print(f"  Safe to use in adversarial training loop.")
    else:
        failed = [k.replace('_pass','') for k in results if k.endswith('_pass') and not results[k]]
        print(f"  ⚠️  OVERALL: FIDELITY CHECK FAILED on: {failed}")
        print(f"  Consider increasing epochs or checking seed data quality.")
    print(f"  {'='*50}")
    
    return results


# =====================================================================
# 4. SAVE / LOAD MODELS
# =====================================================================

def save_model(model, filepath):
    """Save trained CTGAN model to disk."""
    with open(filepath, 'wb') as f:
        pickle.dump(model, f)
    print(f"  💾 Model saved: {filepath}")


def load_model(filepath):
    """Load a trained CTGAN model from disk."""
    import torch
    model = torch.load(filepath, map_location='cpu')
    print(f"  📂 Model loaded: {filepath}")

    return model


